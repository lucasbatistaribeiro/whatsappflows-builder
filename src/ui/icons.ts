export type IconName = keyof typeof ICONS;

export function iconSvg(name: string, size = 16): string {
  const inner = ICONS[name] ?? "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-${name}">${inner}</svg>`;
}

export function iconEl(name: string, size = 16): SVGElement {
  const tpl = document.createElement("template");
  tpl.innerHTML = iconSvg(name, size).trim();
  return tpl.content.firstElementChild as SVGElement;
}

// Replace every <span data-icon="name" [data-size="n"]> in the tree with its icon.
export function applyIcons(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((el) => {
    const name = el.dataset.icon;
    if (!name) return;
    const size = Number(el.dataset.size) || 16;
    el.replaceChildren(iconEl(name, size));
  });
}
